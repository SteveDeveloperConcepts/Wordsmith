// Generates src/engine/data/common-words.ts: the everyday-vocabulary list behind the
// "rare words" statistic. Source: the SCOWL frequency tiers shipped in the
// `wordlist-english` package (tiers 10 and 20, the ~10,000 most common word forms).
//
// Run with: node scripts/build-common-words.mjs
import { createRequire } from 'node:module';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const lists = require('wordlist-english');

const words = new Set();
for (const key of Object.keys(lists)) {
  if (!/\/(?:10|20)$/.test(key)) continue;
  for (const word of lists[key]) {
    const w = word.toLowerCase();
    if (/^[a-z]+$/.test(w)) words.add(w);
  }
}

const sorted = [...words].sort();
const out = resolve(dirname(fileURLToPath(import.meta.url)), '../src/engine/data/common-words.ts');
mkdirSync(dirname(out), { recursive: true });

const lines = [];
let line = '';
for (const w of sorted) {
  if (line.length + w.length + 1 > 110) {
    lines.push(line);
    line = w;
  } else {
    line = line ? `${line} ${w}` : w;
  }
}
if (line) lines.push(line);

writeFileSync(
  out,
  `/**
 * Everyday English vocabulary: the ${sorted.length.toLocaleString('en-US')} most common word forms.
 * Words outside this list count as "rare" in the vocabulary statistics.
 *
 * GENERATED by scripts/build-common-words.mjs from the SCOWL word lists
 * (http://wordlist.aspell.net/), via the \`wordlist-english\` package. Do not edit by hand.
 */
const WORDS = \`
${lines.join('\n')}
\`;

export const COMMON_WORDS: ReadonlySet<string> = new Set(WORDS.trim().split(/\\s+/));
`,
);
console.log(`wrote ${sorted.length} words to ${out}`);
