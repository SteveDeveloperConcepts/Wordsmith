/**
 * Electron's clipboard, shaped for capture.ts. Everything on the clipboard is
 * saved as raw bytes, so whatever the writer last copied comes back intact.
 */
import { ClipboardItem, clipboard } from 'electron';
import type { ClipboardContent, ClipboardPort } from './capture';

type SavedEntry = Record<string, Blob>;

const rawFormat = (name: string) => `electron application/osclipboard;format="${name}"`;

/** 32-bit zero, the value these Windows formats use to mean "no". */
const windowsNo = () => new Blob([new Uint32Array([0])]);

/**
 * Formats that tell the system and clipboard managers to leave this data alone,
 * so a passing correction does not end up in Win+V history or synced to the cloud.
 */
function privacyMarkers(): SavedEntry {
  if (process.platform === 'win32') {
    return {
      [rawFormat('ExcludeClipboardContentFromMonitorProcessing')]: new Blob([]),
      [rawFormat('CanIncludeInClipboardHistory')]: windowsNo(),
      [rawFormat('CanUploadToCloudClipboard')]: windowsNo(),
    };
  }
  if (process.platform === 'darwin') {
    return {
      [rawFormat('org.nspasteboard.TransientType')]: new Blob([]),
      [rawFormat('org.nspasteboard.AutoGeneratedType')]: new Blob([]),
    };
  }
  return {};
}

async function read(item: ClipboardItem, type: string): Promise<string | null> {
  if (!item.types.includes(type)) return null;
  const payload = await item.getType(type);
  return payload instanceof Blob ? payload.text() : null;
}

export const electronClipboard: ClipboardPort<SavedEntry[]> = {
  async save() {
    const saved: SavedEntry[] = [];
    for (const item of await clipboard.read()) {
      const entry: SavedEntry = {};
      for (const type of item.types) {
        try {
          const payload = await item.getType(type);
          if (payload instanceof Blob) entry[type] = payload;
        } catch (err) {
          // One format that cannot be read should not cost the writer the others.
          console.error(`Could not save clipboard format ${type}:`, err);
        }
      }
      if (Object.keys(entry).length > 0) saved.push(entry);
    }
    return saved;
  },

  async restore(saved) {
    if (saved.length === 0) {
      clipboard.clear();
      return;
    }
    await clipboard.write(saved.map((entry) => new ClipboardItem(entry)));
  },

  async read(): Promise<ClipboardContent> {
    const [item] = await clipboard.read();
    if (!item) return { text: '', html: null };
    const text = (await read(item, 'text/plain')) ?? (await clipboard.readText());
    return { text, html: await read(item, 'text/html') };
  },

  async write({ text, html }) {
    const entry: Record<string, string | Blob> = { 'text/plain': text, ...privacyMarkers() };
    if (html !== null) entry['text/html'] = html;
    await clipboard.write([new ClipboardItem(entry)]);
  },
};
